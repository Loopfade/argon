const pattern = new RegExp(Object.keys(english).sort((a,b) => b.length-a.length)
  .map(key => key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'g');

export function t(source, parameters = {}) {
  const translated = language() === 'ru' ? source : source.replace(pattern, key => english[key]);
  return translated.replace(/\{(\w+)\}/g, (token, key) =>
    Object.hasOwn(parameters, key) ? String(parameters[key]) : token);
}

/** Only the initial, static document is translated here; later UI uses t(). */
export function localizePage() {
  document.documentElement.lang = language();
  const walker = document.createTreeWalker(document, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (!['SCRIPT','STYLE'].includes(node.parentElement?.tagName)) node.nodeValue = t(node.nodeValue);
  }
  document.querySelectorAll('*').forEach(node => {
    for (const attribute of ['title','aria-label','placeholder','content']) {
      if (node.hasAttribute(attribute)) node.setAttribute(attribute, t(node.getAttribute(attribute)));
    }
  });
}

